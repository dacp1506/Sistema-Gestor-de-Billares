BEGIN;

CREATE TABLE IF NOT EXISTS sucursales (
  id_sucursal BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  direccion VARCHAR(255),
  telefono VARCHAR(30),
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  username VARCHAR(60),
  email VARCHAR(255) UNIQUE,
  password_hash TEXT NOT NULL,
  rol VARCHAR(30) NOT NULL CHECK (rol IN ('admin_general', 'admin_sucursal', 'cajero')),
  id_sucursal BIGINT REFERENCES sucursales(id_sucursal) ON DELETE RESTRICT,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((rol = 'admin_general' AND id_sucursal IS NULL) OR
         (rol <> 'admin_general' AND id_sucursal IS NOT NULL)),
  CONSTRAINT usuarios_login_identity_check CHECK (
    (rol = 'admin_general' AND email IS NOT NULL) OR
    (rol <> 'admin_general' AND username IS NOT NULL)
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS usuarios_username_lower_uq
  ON usuarios (LOWER(username)) WHERE username IS NOT NULL;

CREATE TABLE IF NOT EXISTS mesas (
  id_mesa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_mesa VARCHAR(20) NOT NULL,
  tipo_mesa VARCHAR(50) NOT NULL,
  tarifa_minuto NUMERIC(10, 2) NOT NULL CHECK (tarifa_minuto > 0),
  estado VARCHAR(20) NOT NULL DEFAULT 'libre'
    CHECK (estado IN ('libre', 'ocupada', 'mantenimiento')),
  activa BOOLEAN NOT NULL DEFAULT TRUE,
  id_sucursal BIGINT NOT NULL REFERENCES sucursales(id_sucursal) ON DELETE RESTRICT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS mesas_numero_activo_por_sucursal
  ON mesas (id_sucursal, numero_mesa) WHERE activa = TRUE;
CREATE INDEX IF NOT EXISTS mesas_sucursal_idx ON mesas (id_sucursal, estado) WHERE activa = TRUE;

CREATE TABLE IF NOT EXISTS sesiones_mesa (
  id_sesion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_mesa BIGINT NOT NULL REFERENCES mesas(id_mesa) ON DELETE RESTRICT,
  id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
  tarifa_minuto NUMERIC(10, 2) NOT NULL CHECK (tarifa_minuto > 0),
  hora_inicio TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  hora_fin TIMESTAMPTZ,
  pausada_en TIMESTAMPTZ,
  segundos_pausa BIGINT NOT NULL DEFAULT 0 CHECK (segundos_pausa >= 0),
  minutos_totales INTEGER NOT NULL DEFAULT 0 CHECK (minutos_totales >= 0),
  total_tiempo NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (total_tiempo >= 0),
  estado VARCHAR(20) NOT NULL DEFAULT 'activa'
    CHECK (estado IN ('activa', 'pausada', 'finalizada')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((estado = 'pausada' AND pausada_en IS NOT NULL) OR estado <> 'pausada'),
  CHECK ((estado = 'finalizada' AND hora_fin IS NOT NULL) OR estado <> 'finalizada')
);
CREATE UNIQUE INDEX IF NOT EXISTS sesiones_una_activa_por_mesa
  ON sesiones_mesa (id_mesa) WHERE estado IN ('activa', 'pausada');

CREATE TABLE IF NOT EXISTS categorias (
  id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL UNIQUE,
  descripcion VARCHAR(255),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS productos (
  id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  precio_venta NUMERIC(10, 2) NOT NULL CHECK (precio_venta >= 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  stock_minimo INTEGER NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
  id_categoria BIGINT REFERENCES categorias(id_categoria) ON DELETE SET NULL,
  id_sucursal BIGINT NOT NULL REFERENCES sucursales(id_sucursal) ON DELETE RESTRICT,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS productos_sucursal_activos_idx
  ON productos (id_sucursal, nombre) WHERE activo = TRUE;

CREATE TABLE IF NOT EXISTS ventas (
  id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha_venta TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  tipo_venta VARCHAR(20) NOT NULL CHECK (tipo_venta IN ('directa', 'mesa')),
  total_productos NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (total_productos >= 0),
  id_sesion BIGINT REFERENCES sesiones_mesa(id_sesion) ON DELETE RESTRICT,
  id_sucursal BIGINT NOT NULL REFERENCES sucursales(id_sucursal) ON DELETE RESTRICT,
  id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
  CHECK ((tipo_venta = 'mesa' AND id_sesion IS NOT NULL) OR
         (tipo_venta = 'directa' AND id_sesion IS NULL))
);
CREATE INDEX IF NOT EXISTS ventas_sucursal_fecha_idx ON ventas (id_sucursal, fecha_venta DESC);

CREATE TABLE IF NOT EXISTS detalle_ventas (
  id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venta BIGINT NOT NULL REFERENCES ventas(id_venta) ON DELETE CASCADE,
  id_producto BIGINT NOT NULL REFERENCES productos(id_producto) ON DELETE RESTRICT,
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  precio_unitario NUMERIC(10, 2) NOT NULL CHECK (precio_unitario >= 0),
  subtotal NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0),
  CHECK (subtotal = ROUND(precio_unitario * cantidad, 2))
);

CREATE TABLE IF NOT EXISTS reservas (
  id_reserva BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_cliente VARCHAR(120) NOT NULL,
  telefono_cliente VARCHAR(30) NOT NULL,
  fecha_reserva DATE NOT NULL,
  hora_inicio TIME NOT NULL,
  duracion_minutos INTEGER NOT NULL CHECK (duracion_minutos > 0),
  estado VARCHAR(20) NOT NULL DEFAULT 'pendiente'
    CHECK (estado IN ('pendiente', 'confirmada', 'cancelada', 'atendida')),
  id_mesa BIGINT NOT NULL REFERENCES mesas(id_mesa) ON DELETE RESTRICT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS reservas_mesa_fecha_idx
  ON reservas (id_mesa, fecha_reserva, hora_inicio)
  WHERE estado IN ('pendiente', 'confirmada');

CREATE TABLE IF NOT EXISTS caja_turnos (
  id_caja BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha_apertura TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  fecha_cierre TIMESTAMPTZ,
  monto_inicial NUMERIC(10, 2) NOT NULL CHECK (monto_inicial >= 0),
  total_calculado NUMERIC(10, 2),
  monto_declarado NUMERIC(10, 2),
  estado VARCHAR(20) NOT NULL DEFAULT 'abierta'
    CHECK (estado IN ('abierta', 'cerrada')),
  id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
  id_sucursal BIGINT NOT NULL REFERENCES sucursales(id_sucursal) ON DELETE RESTRICT,
  CHECK (monto_declarado IS NULL OR monto_declarado >= 0),
  CHECK ((estado = 'abierta' AND fecha_cierre IS NULL) OR
         (estado = 'cerrada' AND fecha_cierre IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS caja_un_turno_abierto_por_usuario
  ON caja_turnos (id_usuario) WHERE estado = 'abierta';
CREATE INDEX IF NOT EXISTS caja_sucursal_apertura_idx ON caja_turnos (id_sucursal, fecha_apertura DESC);

CREATE TABLE IF NOT EXISTS configuraciones_usuario (
  id_configuracion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT NOT NULL UNIQUE REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
  tema VARCHAR(20) NOT NULL DEFAULT 'dark' CHECK (tema IN ('dark', 'light')),
  idioma VARCHAR(10) NOT NULL DEFAULT 'es' CHECK (idioma IN ('es', 'en')),
  moneda VARCHAR(10) NOT NULL DEFAULT 'BOB' CHECK (moneda IN ('BOB', 'USD', 'EUR')),
  nombre_comercial VARCHAR(120) NOT NULL DEFAULT 'SALÓN DE BILLAR BOLA8',
  iva_porcentaje NUMERIC(5, 2) NOT NULL DEFAULT 13
    CHECK (iva_porcentaje >= 0 AND iva_porcentaje <= 30),
  formato_impresion VARCHAR(10) NOT NULL DEFAULT '80mm'
    CHECK (formato_impresion IN ('80mm', 'A4')),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMIT;
