BEGIN;

-- Módulo de mantenimiento de equipos del salón de billar.
-- Adaptación del caso LabCare al dominio Bola8: el catálogo de equipos
-- (mesas, bolas, tacos, iluminación) pertenece a una sucursal y las
-- solicitudes conservan trazabilidad mediante eliminación lógica.

CREATE TABLE IF NOT EXISTS equipos (
  id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(20) NOT NULL UNIQUE,
  nombre VARCHAR(120) NOT NULL,
  ubicacion VARCHAR(160) NOT NULL,
  estado VARCHAR(30) NOT NULL DEFAULT 'OPERATIVO'
    CHECK (estado IN ('OPERATIVO', 'FUERA_DE_SERVICIO', 'MANTENIMIENTO')),
  id_sucursal BIGINT NOT NULL REFERENCES sucursales(id_sucursal) ON DELETE RESTRICT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS equipos_sucursal_estado_idx
  ON equipos (id_sucursal, estado);

CREATE TABLE IF NOT EXISTS solicitudes_mantenimiento (
  id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_solicitud VARCHAR(30) NOT NULL UNIQUE,
  id_equipo BIGINT NOT NULL REFERENCES equipos(id_equipo) ON DELETE RESTRICT,
  id_sucursal BIGINT NOT NULL REFERENCES sucursales(id_sucursal) ON DELETE RESTRICT,
  solicitante VARCHAR(120) NOT NULL,
  descripcion TEXT NOT NULL,
  prioridad VARCHAR(10) NOT NULL CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA')),
  estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
    CHECK (estado IN ('PENDIENTE', 'EN_PROCESO', 'RESUELTA', 'CANCELADA')),
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  CHECK (LENGTH(BTRIM(solicitante)) >= 3),
  CHECK (LENGTH(BTRIM(solicitante)) <= 120),
  CHECK (LENGTH(BTRIM(descripcion)) >= 10),
  CHECK (LENGTH(BTRIM(descripcion)) <= 2000)
);
CREATE INDEX IF NOT EXISTS solicitudes_mantenimiento_activas_idx
  ON solicitudes_mantenimiento (id_sucursal, activo, fecha_registro DESC);
CREATE INDEX IF NOT EXISTS solicitudes_mantenimiento_equipo_idx
  ON solicitudes_mantenimiento (id_equipo);
CREATE INDEX IF NOT EXISTS solicitudes_mantenimiento_estado_idx
  ON solicitudes_mantenimiento (id_sucursal, estado)
  WHERE activo = TRUE;

-- Datos semilla adaptados al salón de billar. Se cargan en la primera
-- sucursal existente para respetar el alcance multi-sucursal del sistema.
INSERT INTO equipos (codigo, nombre, ubicacion, estado, id_sucursal)
SELECT seed.codigo, seed.nombre, seed.ubicacion, seed.estado, sucursal.id_sucursal
FROM (
  VALUES
    ('EQ-001', 'Mesa de billar profesional', 'Salón Principal', 'OPERATIVO'),
    ('EQ-002', 'Juego de bolas de billar', 'Mesa 1', 'OPERATIVO'),
    ('EQ-003', 'Taco de billar profesional', 'Área de juego', 'OPERATIVO'),
    ('EQ-004', 'Lámpara colgante de mesa', 'Salón Principal', 'OPERATIVO')
) AS seed(codigo, nombre, ubicacion, estado)
CROSS JOIN (
  SELECT id_sucursal FROM sucursales ORDER BY id_sucursal LIMIT 1
) AS sucursal
ON CONFLICT (codigo) DO NOTHING;

COMMIT;
