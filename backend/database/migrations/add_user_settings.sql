-- Preferencias de la aplicación por usuario autenticado.
-- Cada cuenta guarda su propia configuración (tema, idioma, moneda y datos
-- de facturación/impresión del comprobante).
CREATE TABLE IF NOT EXISTS configuraciones_usuario (
  id_configuracion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT NOT NULL UNIQUE REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
  tema VARCHAR(20) NOT NULL DEFAULT 'dark' CHECK (tema IN ('dark', 'light')),
  idioma VARCHAR(10) NOT NULL DEFAULT 'es' CHECK (idioma IN ('es', 'en')),
  moneda VARCHAR(10) NOT NULL DEFAULT 'BOB' CHECK (moneda IN ('BOB', 'USD', 'EUR')),
  nombre_comercial VARCHAR(120) NOT NULL DEFAULT 'SALÓN DE BILLAR BOLA8',
  iva_porcentaje NUMERIC(5, 2) NOT NULL DEFAULT 13
    CHECK (iva_porcentaje >= 0 AND iva_porcentaje <= 30),
  formato_impresion VARCHAR(10) NOT NULL DEFAULT '80mm'
    CHECK (formato_impresion IN ('80mm', 'A4')),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMIT;
